-- ===================
-- #6 Ranking Analysis: Order the values of DIMENSION by MEASURE. Top N Performers | Bottom N Performers
-- ===================

-- FORMULA: RANK[DIMESION] BY SUMATION[MEASURE] LIKE RANK COUNTRIES BY TOTAL ORDERS, TOP 5 PRODUCTS BY QUANTITY, BOTTOM 3 CUSTOMERS BY TOTAL ORDERS

-- # TASK:
-- WHICH 5 PRODUCTS GENERATE THE HIGHEST REVENUE (Top N Performers)
SELECT TOP 5
P.product_name,
SUM(S.sales_amount) AS TOTAL_REVENUE
FROM gold.fact_sales AS S
LEFT JOIN gold.dim_products AS P
ON S.product_key = P.product_key
GROUP BY P.product_name
ORDER BY TOTAL_REVENUE DESC

--OR --> WINDOW FUNCTION(FOR MORE FLEXIBLE AND COMPLEX QUERIES WITH EXTRA DETAILS)
SELECT *
FROM(
SELECT
product_name,
SUM(S.sales_amount) AS TOTAL_SALES,
RANK() OVER(ORDER BY SUM(S.sales_amount) DESC) AS PRODUCT_RANK
FROM gold.fact_sales AS S
LEFT JOIN gold.dim_products P
ON S.product_key = P.product_key
GROUP BY product_name
)T 
WHERE PRODUCT_RANK <= 5

-- WHAT ARE THE 5 WORST-PERFORMING PRODUCTS IN TERMS OF SALES (Bottom N Performers)

SELECT TOP 5
P.product_name,
SUM(S.sales_amount) AS TOTAL_SALES -- OR TOTAL_REVENUE BOTH ARE SAME
FROM gold.fact_sales AS S
LEFT JOIN gold.dim_products AS P
ON S.product_key = P.product_key
GROUP BY P.product_name
ORDER BY TOTAL_SALES ASC

-- FIND THE TOP 10 CUSTOMERS WHO HAVE GENERATED THE HIGHEST REVENUE.
SELECT TOP 10
C.customer_key,
C.first_name,
C.last_name,
SUM(S.sales_amount) AS TOTAL_REVENUE
FROM gold.fact_sales AS S
LEFT JOIN  gold.dim_customers AS C
ON S.customer_key = C.customer_key
GROUP BY C.customer_key,
		 C.first_name,
		 C.last_name
ORDER BY TOTAL_REVENUE DESC

-- FIND THE TOP 3 CUSTOMERS WITH THE FEWEST ORDERS PLACED.
SELECT TOP 3
C.customer_key,
C.first_name,
C.last_name,
COUNT(DISTINCT S.order_number) AS TOTAL_ORDERS
FROM gold.fact_sales AS S
LEFT JOIN  gold.dim_customers AS C
ON S.customer_key = C.customer_key
GROUP BY C.customer_key,
		 C.first_name,
		 C.last_name
ORDER BY TOTAL_ORDERS ASC
