
-- ======================
--  #5 MAGNITUDE ANALYSIS: COMPARE THE MEASURE VALUES BY CATEGORIES. IT HELP US UNDERSTAND THE IMPORTANCE OF DIFFERENCE CATEGORIES.
-- ======================

-- FORMULA: SUM[MEASURE] BY[DIMENSION] LIKE TOTAL SALES BY COUNTRY, TOTAL QUANTITY BY CATEGORY, AVGERAGE PRICE BY PRODUCT, TOTAL ORDERS BY CUSTOMER

-- #1 TASK:

-- FIND TOTAL CUSTOMERS BY COUNTRIES
SELECT 
country,
COUNT(customer_key) AS TOTAL_CUSTOMERS_BY_COUNTRY
FROM gold.dim_customers
GROUP BY country
ORDER BY TOTAL_CUSTOMERS_BY_COUNTRY DESC
-- FIND TOTAL CUSTOMERS BY GENDER
SELECT 
gender,
COUNT(gender) AS TOTAL_CUSTOMERS_BY_GENDER
FROM gold.dim_customers
GROUP BY gender
ORDER BY TOTAL_CUSTOMERS_BY_GENDER DESC
-- FIND TOTAL PRODUCTS BY CATEGORY
SELECT 
category,
COUNT(product_key) AS TOTAL_PRODUCTS_BY_CATEGORY
FROM gold.dim_products
GROUP BY category
ORDER BY TOTAL_PRODUCTS_BY_CATEGORY DESC
-- WHAT IS THE AVERAGE COST IN EACH CATEGORY?
SELECT 
category,
AVG(product_cost) AS AVG_COST_BY_CATEGORY
FROM gold.dim_products
GROUP BY category
ORDER BY AVG_COST_BY_CATEGORY DESC
-- WHAT IS THE TOTAL REVENUE GENERATED FOR EACH CATEGORY?
SELECT 
P.category,
SUM(S.sales_amount) AS TOTAL_REVENUE_BY_CATEGORY
FROM gold.fact_sales AS S
LEFT JOIN gold.dim_products P
ON S.product_key = P.product_key
GROUP BY P.category
ORDER BY TOTAL_REVENUE_BY_CATEGORY DESC
-- FIND TOTAL REVENUE GENERATED BY EACH CUSTOMER
SELECT 
C.customer_key,
C.first_name,
C.last_name,
SUM(S.sales_amount) AS TOAL_REVENUE_BY_CUSTOMER
FROM gold.fact_sales AS S
LEFT JOIN gold.dim_customers AS C
ON S.customer_key = C.customer_key
GROUP BY C.customer_key,
         C.first_name,
         C.last_name
ORDER BY TOAL_REVENUE_BY_CUSTOMER DESC
-- WHAT IS THE DISTRIBUTION OF SOLD ITEMS ACROSS COUNTRIES?
SELECT 
C.country,
SUM(S.quantity) AS ITEM_SOLD_BY_COUNTRY
FROM gold.fact_sales AS S
LEFT JOIN gold.dim_customers AS C
ON S.customer_key = C.customer_key
GROUP BY C.country
ORDER BY ITEM_SOLD_BY_COUNTRY DESC

-- WHAT IS THE DISTRIBUTION OF SOLD ITEMS ACROSS COUNTRIES BY PRODUCT?-- mINE  qUESTION
SELECT 
P.category,
C.country,
SUM(S.sales_amount) AS TOAL_REVENUE_BY_PRODUCT
FROM gold.dim_products AS P
LEFT JOIN gold.fact_sales AS S
ON P.product_key = S.product_key
LEFT JOIN gold.dim_customers AS C
ON S.customer_key = C.customer_key
GROUP BY P.category, C.country
ORDER BY country

